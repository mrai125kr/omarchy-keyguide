    def test_metadata_is_complete_and_deterministic(self) -> None:
        """Nondeterministic metadata would make safe external-edit detection impossible."""
        first = ManagedShortcutEntry(
            id="new-zed",
            kind="new",
            source_binding_id=None,
            original=None,
            current=self.action(key="Z", description="Zed", action_argument="zed"),
        )
        second = ManagedShortcutEntry(
            id="new-browser",
            kind="new",
            source_binding_id=None,
            original=None,
            current=self.action(key="B", description="Browser", action_argument="chromium"),
        )

        generated = ManagedShortcutState(entries=(first, second)).to_bytes()
        metadata_line = generated.splitlines()[1].decode("ascii")
        encoded = metadata_line.removeprefix("-- keyguide-state: ")
        padding = "=" * (-len(encoded) % 4)
        document = json.loads(base64.urlsafe_b64decode(encoded + padding))

        self.assertEqual(4, document["version"])
        self.assertEqual([], document["suppressed"])
        self.assertEqual(["new-browser", "new-zed"], [item["id"] for item in document["entries"]])
        self.assertEqual(
            generated,
            ManagedShortcutState(entries=(second, first)).to_bytes(),
        )

