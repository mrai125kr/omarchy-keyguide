        manager.remove(self.remove_request(manager=manager, key="C"))
        before = manager.path.read_bytes()
        changed = False

        def changed_restore_runner(command: tuple[str, ...]) -> str:
            nonlocal changed
            result = self.runner(command)
            if command == ("hyprctl", "reload") and not changed:
                changed = True
                self.hyprctl = self.runtime_record(
                    "C",
                    "Callback",
                    "452",
                    dispatcher="__lua",
                )
            return result

        manager.runner = changed_restore_runner

        with self.assertRaisesRegex(
            ShortcutMutationError,
            "restored different shortcut metadata; change was rolled back",
        ):
            manager.reset()

        self.assertEqual(before, manager.path.read_bytes())

