    def remove_request(
        self,
        *,
        manager: ShortcutManager | None = None,
        key: str = "A",
        confirm_remove: bool = True,
    ) -> dict[str, object]:
        current = manager or self.manager()
        binding = next(
            item
            for item in current.bindings()
            if bindings.canonical_key(item.key) == key
        )
        return {
            "targetModifiers": list(binding.modifiers),
            "targetKey": bindings.canonical_key(binding.key),
            "targetBindingId": binding.id,
            "title": binding.description,
            "dispatcher": binding.dispatcher or "",
            "argument": binding.argument or "",
            "confirmRemove": confirm_remove,
        }

