    def runner(self, command: tuple[str, ...]) -> str:
        self.calls.append(command)
        if self.base_hyprctl is None and command in {
            ("omarchy", "menu", "keybindings", "--print"),
            ("hyprctl", "binds"),
        }:
            self.base_menu = self.menu
            self.base_hyprctl = self.hyprctl
            self.base_source_records = self.source_records
        if command == ("omarchy", "menu", "keybindings", "--print"):
            return self.menu
        if command == ("hyprctl", "binds"):
            return self.hyprctl
        if command == (
            "/usr/bin/bash",
            "-c",
            "source /usr/bin/omarchy-menu-keybindings --print >/dev/null; "
            "output_binding_records",
        ):
            if self.source_discovery_error is not None:
                raise self.source_discovery_error
            return self.source_records
        if (
            len(command) == 4
            and command[:2] == ("hyprctl", "getoption")
            and command[3] == "-j"
        ):
            name = command[2].removeprefix("input:")
            if name not in self.keyboard_options:
                raise AssertionError(f"unexpected keyboard option: {name}")
            return json.dumps(
                {
                    "option": command[2],
                    "str": self.keyboard_options[name],
                    "set": True,
                }
            )
        if command[:2] == ("xkbcli", "compile-keymap"):
            return self.compiled_keymap
        if command == ("hyprctl", "reload"):
            self.emulate_reload()
            return "ok\n"
        if command == ("hyprctl", "configerrors"):
            return self.config_errors
        if command == ("omarchy-default-browser",):
            return self.default_browser + "\n"
        if command == (
            "env", "-u", "BROWSER", "xdg-settings", "get", "default-web-browser"
        ):
            return {
                "chromium": "chromium.desktop",
                "chrome": "google-chrome.desktop",
                "brave": "brave-browser.desktop",
                "brave-origin": "brave-origin.desktop",
                "edge": "microsoft-edge.desktop",
                "firefox": "firefox.desktop",
                "zen": "zen.desktop",
            }.get(self.default_browser, self.default_browser) + "\n"
        if command == ("omarchy-default-editor",):
            return self.default_editor + "\n"
        raise AssertionError(f"unexpected command: {command}")

    def emulate_reload(self) -> None:
        """Project the generated module onto the immutable fixture baseline."""
        if self.base_hyprctl is None:
            self.base_menu = self.menu
            self.base_hyprctl = self.hyprctl
            self.base_source_records = self.source_records
        assert self.base_menu is not None
        assert self.base_source_records is not None
        runtime = list(bindings.parse_runtime_bindings(self.base_hyprctl))
        displayed = list(
            bindings.parse(
                self.base_menu,
                self.base_hyprctl,
                self.base_source_records,
            )
        )
        managed_path = (
            self.state_home
            / "omarchy"
            / "toggles"
            / "hypr"
            / "omarchy-keyguide.lua"
        )
        state = (
            ManagedShortcutState.from_bytes(managed_path.read_bytes())
            if managed_path.exists()
            else ManagedShortcutState.empty()
        )
        suppressed_chords = {item.chord for item in state.suppressed}
        suppressed_chords.update(
            entry.original.chord
            for entry in state.entries
            if entry.original is not None
        )
        runtime = [
            item
            for item in runtime
            if (item.modifiers, bindings.canonical_key(item.key))
            not in suppressed_chords
        ]
        displayed = [
            item
            for item in displayed
            if (item.modifiers, bindings.canonical_key(item.key))
            not in suppressed_chords
        ]
        for entry in state.entries:
            current = entry.current
            runtime.append(
                bindings.RuntimeBinding(
                    modifiers=current.modifiers,
                    key=current.key,
                    description=current.description,
                    dispatcher="__lua",
                    argument=str(9000 + len(runtime)),
                )
            )
            displayed.append(
                bindings.Binding(
                    id=bindings.stable_id(
                        current.modifiers,
                        current.key,
                        current.description,
                    ),
                    modifiers=current.modifiers,
                    key=current.key,
                    description=current.description,
                    dispatcher="exec" if current.action_kind == "exec" else "__lua",
                    argument=current.action_argument,
                    mouse=False,
                    editable=True,
                    action_kind=current.action_kind,
                    action_argument=current.action_argument,
                )
            )
        self.hyprctl = "".join(
            self.runtime_record(
                item.key,
                item.description,
                item.argument or "",
                modmask=sum(
                    {"SUPER": 64, "CTRL": 4, "SHIFT": 1, "ALT": 8}[modifier]
                    for modifier in item.modifiers
                ),
                dispatcher=item.dispatcher or "",
            )
            for item in runtime
        )
        self.menu = "".join(
            f"{' '.join(item.modifiers)} + {item.key} → {item.description}\n"
            for item in displayed
        )
        self.source_records = "".join(
            f"{' '.join(item.modifiers)} + {item.key} → {item.description}\t"
            f"{item.action_kind or ''}\t{item.action_argument or ''}\n"
            for item in displayed
        )

