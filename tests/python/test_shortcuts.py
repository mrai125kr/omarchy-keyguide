        generated = ManagedShortcutState(entries=(entry,)).to_bytes()

        self.assertIn(b'hl.unbind("SUPER + RETURN")\n', generated)
        self.assertIn(
            b'o.bind("SUPER + SHIFT + T", "Terminal \\"Work\\"", '
            b'"uwsm-app -- alacritty --working-directory C:\\\\Work")\n',
            generated,
        )
        self.assertEqual(
            ManagedShortcutState(entries=(entry,)),
            ManagedShortcutState.from_bytes(generated),
        )

