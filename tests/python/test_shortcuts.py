    def test_reset_all_settings_rollback_failure_keeps_journal_for_next_status_recovery(self) -> None:
        """A failed in-process rollback must preserve durable recovery evidence."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            test_case = ShortcutManagerTests(methodName="runTest")
            test_case.setUp()
            self.addCleanup(test_case.tearDown)
            manager = test_case.manager()
            manager.move(
                test_case.move_request(
                    target_modifiers=["SUPER"],
                    target_key="N",
                )
            )
            shortcut_preimage = manager.path.read_bytes()
            settings_path = root / "data" / "omarchy-keyguide" / "settings.json"
            prior_settings = settings.Settings.defaults().update({"opacity": 0.61})
            prior_settings.save_atomic(settings_path)
            settings_preimage = settings_path.read_bytes()
            real_save = settings.Settings.save_atomic
            real_restore = settings.restore_file_snapshot
            restore_calls = 0

            def fail_after_replace(document: settings.Settings, path: str | Path) -> None:
                real_save(document, path)
                raise OSError("simulated settings commit acknowledgement failure")

            def fail_first_restore(
                path: str | Path,
                snapshot: settings.SettingsFileSnapshot,
            ) -> None:
                nonlocal restore_calls
                restore_calls += 1
                if restore_calls == 1:
                    raise OSError("simulated settings rollback failure")
                real_restore(path, snapshot)

            output = io.StringIO()
            with (
                patch.dict(
                    os.environ,
                    {"XDG_DATA_HOME": str(root / "data")},
                    clear=False,
                ),
                patch.object(cli.shortcuts, "ShortcutManager", return_value=manager),
                patch.object(settings.Settings, "save_atomic", fail_after_replace),
                patch.object(
                    settings,
                    "restore_file_snapshot",
                    side_effect=fail_first_restore,
                ),
                patch.object(
                    sys,
                    "argv",
                    ["keyguide_backend", "shortcuts", "reset-all"],
                ),
                redirect_stdout(output),
            ):
                with self.assertRaisesRegex(ShortcutMutationError, "settings rollback failed"):
                    cli.main()

            self.assertEqual("", output.getvalue())
            self.assertTrue(manager.reset_journal_path.exists())
            self.assertEqual(shortcut_preimage, manager.path.read_bytes())
            self.assertNotEqual(settings_preimage, settings_path.read_bytes())

            with (
                patch.dict(
                    os.environ,
                    {"XDG_DATA_HOME": str(root / "data")},
                    clear=False,
                ),
                patch.object(cli.shortcuts, "ShortcutManager", return_value=manager),
                patch.object(
                    sys,
                    "argv",
                    ["keyguide_backend", "shortcuts", "status"],
                ),
                redirect_stdout(output),
            ):
                self.assertEqual(0, cli.main())

            self.assertEqual(shortcut_preimage, manager.path.read_bytes())
            self.assertEqual(settings_preimage, settings_path.read_bytes())
            self.assertFalse(manager.reset_journal_path.exists())

