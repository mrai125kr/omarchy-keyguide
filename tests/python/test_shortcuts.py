    def test_reset_all_finalizes_before_waiting_peer_can_recover(self) -> None:
        """A refresh waiting on the reset lock must not roll back a successful reset."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            test_case = ShortcutManagerTests(methodName="runTest")
            test_case.setUp()
            self.addCleanup(test_case.tearDown)
            manager = test_case.manager()
            peer = test_case.manager()
            manager.move(test_case.move_request(target_key="N"))
            settings_path = root / "data" / "omarchy-keyguide" / "settings.json"
            prior_settings = settings.Settings.defaults().update({"opacity": 0.61})
            prior_settings.save_atomic(settings_path)

            journal_created = threading.Event()
            peer_waiting = threading.Event()
            peer_finished = threading.Event()
            peer_results: list[bool] = []
            peer_errors: list[BaseException] = []
            real_write_journal = manager._write_reset_journal
            real_peer_locked = peer._locked
            real_reset = manager.reset

            def coordinated_write_journal(*args: object) -> None:
                real_write_journal(*args)  # type: ignore[arg-type]
                journal_created.set()
                if not peer_waiting.wait(5):
                    raise AssertionError("peer did not reach the reset lock")

            @contextmanager
            def observed_peer_lock():
                peer_waiting.set()
                with real_peer_locked():
                    yield

            def recover_in_peer() -> None:
                try:
                    if not journal_created.wait(5):
                        raise AssertionError("reset journal was not created")
                    peer_results.append(peer.recover_reset_transaction(settings_path))
                except BaseException as error:
                    peer_errors.append(error)
                finally:
                    peer_finished.set()

            def coordinated_reset(**kwargs: object) -> dict[str, object]:
                result = real_reset(**kwargs)  # type: ignore[arg-type]
                if not peer_finished.wait(5):
                    raise AssertionError("peer recovery did not finish after reset unlock")
                return result

            output = io.StringIO()
            peer_thread = threading.Thread(target=recover_in_peer, daemon=True)
            with (
                patch.dict(
                    os.environ,
                    {"XDG_DATA_HOME": str(root / "data")},
                    clear=False,
                ),
                patch.object(cli.shortcuts, "ShortcutManager", return_value=manager),
                patch.object(
                    manager,
                    "_write_reset_journal",
                    side_effect=coordinated_write_journal,
                ),
                patch.object(peer, "_locked", observed_peer_lock),
                patch.object(manager, "reset", side_effect=coordinated_reset),
                patch.object(
                    sys,
                    "argv",
                    ["keyguide_backend", "shortcuts", "reset-all"],
                ),
                redirect_stdout(output),
            ):
                peer_thread.start()
                self.assertEqual(0, cli.main())

            peer_thread.join(5)
            self.assertFalse(peer_thread.is_alive())
            if peer_errors:
                raise peer_errors[0]
            self.assertEqual([False], peer_results)
            self.assertFalse(manager.reset_journal_path.exists())
            self.assertEqual(
                0,
                json.loads(output.getvalue())["shortcuts"]["managedCount"],
            )
            self.assertEqual(
                ManagedShortcutState.empty(),
                ManagedShortcutState.from_bytes(manager.path.read_bytes()),
            )
            self.assertEqual(settings.Settings.defaults(), settings.Settings.load(settings_path))

