        state = ManagedShortcutState(
            entries=(replacement,),
            suppressed=(suppression,),
        )
        generated = state.to_bytes()
        restored = ManagedShortcutState.from_bytes(generated)

        self.assertEqual(state, restored)
        self.assertEqual(4, decoded_metadata(generated)["version"])
        self.assertLess(
            generated.index(b'hl.unbind("SUPER + A")'),
            generated.index(b'o.bind("SUPER + A"'),
        )

