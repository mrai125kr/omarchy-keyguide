def decoded_metadata(value: bytes) -> object:
    encoded = value.splitlines()[1].decode("ascii").removeprefix(
        "-- keyguide-state: "
    )
    return json.loads(base64.urlsafe_b64decode(encoded + "=" * (-len(encoded) % 4)))


def legacy_v1_state_bytes(*, command: str) -> bytes:
    document = {
        "version": 1,
        "entries": [
            {
                "id": "new-alpha",
                "kind": "new",
                "sourceBindingId": None,
                "original": None,
                "current": {
                    "modifiers": ["SUPER"],
                    "key": "A",
                    "description": "Alpha",
                    "command": command,
                },
            }
        ],
    }
    metadata = json.dumps(
        document,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")
    encoded = base64.urlsafe_b64encode(metadata).rstrip(b"=").decode("ascii")
    return (
        "-- Omarchy Keyguide managed shortcuts v1\n"
        f"-- keyguide-state: {encoded}\n"
        "-- Generated by Omarchy Keyguide. Use Settings instead of editing this file.\n"
        f'o.bind("SUPER + A", "Alpha", "{command}")\n'
    ).encode("utf-8")


class ManagedShortcutStateTests(unittest.TestCase):
    """Catch unsafe or non-canonical generated shortcut modules."""

    def action(
        self,
        *,
        modifiers: tuple[str, ...] = ("SUPER",),
        key: str = "RETURN",
        description: str = "Terminal",
        action_kind: str = "exec",
        action_argument: str = "alacritty",
    ) -> ShortcutAction:
        return ShortcutAction(
            modifiers=modifiers,
            key=key,
            description=description,
            action_kind=action_kind,
            action_argument=action_argument,
        )

    def test_empty_state_is_a_valid_noop_module(self) -> None:
        """Reset must publish valid Lua without leaving any binding action."""
        state = ManagedShortcutState.empty()

        generated = state.to_bytes()

        self.assertEqual(state, ManagedShortcutState.from_bytes(generated))
        self.assertTrue(generated.startswith(b"-- Omarchy Keyguide managed shortcuts v4\n"))
        self.assertIn(b"-- No managed shortcuts.\n", generated)
        self.assertNotIn(b"hl.unbind(", generated)
        self.assertNotIn(b"o.bind(", generated)

    def test_lua_dispatcher_accepts_only_scanner_expression_grammar(self) -> None:
        valid = 'hl.dsp.window.move({ follow = false, workspace = "10" })'
        self.assertEqual(
            valid,
            shortcuts_module.validate_lua_dispatcher_expression(valid),
        )
        for invalid in (
            'os.execute("touch /tmp/no")',
            'hl.dsp.window.close(); os.execute("touch /tmp/no")',
            '(function() return hl.dsp.window.close() end)()',
            'hl.dsp.window.close() -- trailing',
        ):
            with self.subTest(invalid=invalid):
                with self.assertRaises(ShortcutValidationError):
                    shortcuts_module.validate_lua_dispatcher_expression(invalid)

    def test_lua_dispatcher_supports_each_literal_and_table_entry_form(self) -> None:
        valid = (
            "hl.dsp.window.move(-12.5e+2, true, false, nil, "
            "{ 'value', name = \"escaped \\\"text\\\"\", [2] = { nested = {}, }, })"
        )

        self.assertEqual(
            valid,
            shortcuts_module.validate_lua_dispatcher_expression(valid),
        )

    def test_lua_dispatcher_rejects_malformed_values_and_boundaries(self) -> None:
        for invalid in (
            "hl.dsp.window.close(",
            "hl.dsp.window.close(1e9999)",
            "hl.dsp.window.close(callback)",
            "hl.dsp.window.close({ key = })",
            "hl.dsp.window.close({ true = 1 })",
            "hl.dsp.window.close(1 + 2)",
            "hl.dsp.window.close()) trailing",
            "hl.dsp.end.close()",
            "hl.dsp.window.close(\u00a0)",
            'hl.dsp.window.close("bad\u0085value")',
        ):
            with self.subTest(invalid=invalid):
                with self.assertRaises(ShortcutValidationError):
                    shortcuts_module.validate_lua_dispatcher_expression(invalid)

    def test_version_one_exec_state_migrates_to_canonical_version_four(self) -> None:
        legacy = legacy_v1_state_bytes(command="alpha-command")
        state = ManagedShortcutState.from_bytes(legacy)
        self.assertEqual("exec", state.entries[0].current.action_kind)
        self.assertEqual("alpha-command", state.entries[0].current.action_argument)
        self.assertEqual(4, decoded_metadata(state.to_bytes())["version"])
        self.assertEqual((), state.suppressed)
        self.assertEqual("", state.entries[0].selection_kind)
        self.assertEqual("", state.entries[0].label_key)

        with self.assertRaisesRegex(ShortcutValidationError, "canonical"):
            ManagedShortcutState.from_bytes(legacy + b"-- manual legacy edit\n")

    def test_version_one_exec_state_preserves_legacy_non_ascii_control(self) -> None:
        command = "alpha\u0085command"
